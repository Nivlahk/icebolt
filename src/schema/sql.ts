import type { CompiledColumn, CompiledSchema, CompiledTable } from '../types.js';

export const META_TABLE = '__icebolt_meta';
export const COMPILER_VERSION = '1.0.0';

export function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

export function quoteLiteral(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

export function columnDefinition(table: CompiledTable, col: CompiledColumn): string {
  const parts: string[] = [quoteIdent(col.name), col.sqlType];
  const singlePk = table.primaryKey.length === 1 && table.primaryKey[0] === col.name;
  if (singlePk) {
    parts.push('PRIMARY KEY');
    if (col.autoIncrement) parts.push('AUTOINCREMENT');
  }
  if (!col.nullable && !(singlePk && col.sqlType === 'INTEGER')) parts.push('NOT NULL');
  if (col.unique && !singlePk) parts.push('UNIQUE');
  if (col.defaultSql !== null) parts.push(`DEFAULT ${col.defaultSql}`);

  const checks: string[] = [];
  const q = quoteIdent(col.name);
  if (col.kind === 'boolean') checks.push(`${q} IN (0, 1)`);
  if (col.kind === 'enum' && col.enumValues) checks.push(`${q} IN (${col.enumValues.map(quoteLiteral).join(', ')})`);
  if (col.kind === 'json') checks.push(`json_valid(${q})`);
  if (col.maxLength !== null) checks.push(`length(${q}) <= ${col.maxLength}`);
  checks.push(...col.checks);
  for (const c of checks) parts.push(`CHECK (${c})`);
  return parts.join(' ');
}

export function createTableSql(table: CompiledTable, strict: boolean): string {
  const lines = table.columns.map((c) => `  ${columnDefinition(table, c)}`);
  if (table.primaryKey.length > 1) {
    lines.push(`  PRIMARY KEY (${table.primaryKey.map(quoteIdent).join(', ')})`);
  }
  for (const fk of table.foreignKeys) {
    let clause = `  FOREIGN KEY (${fk.columns.map(quoteIdent).join(', ')}) REFERENCES ${quoteIdent(fk.refTable)} (${fk.refColumns.map(quoteIdent).join(', ')})`;
    if (fk.onDelete) clause += ` ON DELETE ${fk.onDelete}`;
    if (fk.onUpdate) clause += ` ON UPDATE ${fk.onUpdate}`;
    lines.push(clause);
  }
  return `CREATE TABLE IF NOT EXISTS ${quoteIdent(table.name)} (\n${lines.join(',\n')}\n)${strict ? ' STRICT' : ''};`;
}

export function createIndexSql(table: CompiledTable): string[] {
  return table.indexes.map((idx) => {
    const cols = idx.parts.map((p) => (p.kind === 'column' ? quoteIdent(p.value) : `(${p.value})`)).join(', ');
    return `CREATE ${idx.unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS ${quoteIdent(idx.name)} ON ${quoteIdent(table.name)} (${cols});`;
  });
}

/** DDL body only (no transaction / meta rows) — this is what gets fingerprinted. */
export function emitDdl(schema: CompiledSchema, strict: boolean): string {
  const out: string[] = [];
  for (const t of schema.tables) {
    out.push(createTableSql(t, strict));
    out.push(...createIndexSql(t));
    out.push('');
  }
  return out.join('\n').trimEnd();
}

/** Meta rows that record which schema (and which version of it) a database holds. */
export function schemaMetaSql(schemaHash: string, version: number, snapshotJson: string): string[] {
  const t = quoteIdent(META_TABLE);
  return [
    `INSERT OR REPLACE INTO ${t} ("key", "value") VALUES ('schema_hash', ${quoteLiteral(schemaHash)});`,
    `INSERT OR REPLACE INTO ${t} ("key", "value") VALUES ('schema_version', ${quoteLiteral(String(version))});`,
    `INSERT OR REPLACE INTO ${t} ("key", "value") VALUES ('schema_snapshot', ${quoteLiteral(snapshotJson)});`,
    `INSERT OR REPLACE INTO ${t} ("key", "value") VALUES ('compiler_version', ${quoteLiteral(COMPILER_VERSION)});`,
  ];
}

export function emitMigration(ddl: string, schemaHash: string, strict: boolean, snapshot?: { version: number; json: string }): string {
  return [
    '-- Generated by @icebolt/compiler-core. Do not edit by hand.',
    `-- schema-hash: ${schemaHash}`,
    'PRAGMA foreign_keys = ON;',
    'BEGIN;',
    `CREATE TABLE IF NOT EXISTS ${quoteIdent(META_TABLE)} (`,
    '  "key" TEXT PRIMARY KEY NOT NULL,',
    '  "value" TEXT NOT NULL',
    `)${strict ? ' STRICT' : ''};`,
    '',
    ddl,
    '',
    ...(snapshot
      ? schemaMetaSql(schemaHash, snapshot.version, snapshot.json)
      : [
          `INSERT OR REPLACE INTO ${quoteIdent(META_TABLE)} ("key", "value") VALUES ('schema_hash', ${quoteLiteral(schemaHash)});`,
          `INSERT OR REPLACE INTO ${quoteIdent(META_TABLE)} ("key", "value") VALUES ('compiler_version', ${quoteLiteral(COMPILER_VERSION)});`,
        ]),
    `INSERT OR IGNORE INTO ${quoteIdent(META_TABLE)} ("key", "value") VALUES ('created_at', strftime('%Y-%m-%dT%H:%M:%fZ', 'now'));`,
    'COMMIT;',
    '',
  ].join('\n');
}
